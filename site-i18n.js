  const preferred = navigator.languages?.map(normalize).find(Boolean);
  const initial = requested || saved || preferred || "uk";
  const selects = document.querySelectorAll(".language-control select");

  function updateInternalLinks(locale) {
    document.querySelectorAll("a[href]").forEach((link) => {
      const href = link.getAttribute("href");
      if (!href || href.startsWith("#")) return;

      const url = new URL(href, location.href);
      if (url.origin !== location.origin) return;
      if (!url.pathname.endsWith(".html") && !url.pathname.endsWith("/")) return;

      url.searchParams.set("lang", locale);
      link.href = url.href;
    });
  }

  function applyPageFragments(page, locale) {
    const pageTranslations = window.PATRON_PAGE_TRANSLATIONS?.[page];
    const fragments = pageTranslations?.[locale] || pageTranslations?.uk;
    if (!fragments) return;

    Object.entries(fragments).forEach(([key, html]) => {
      const element = document.querySelector(`[data-page-fragment="${key}"]`);
      if (element) element.innerHTML = html;
    });
  }

  function ensureTopAppStoreBadge() {
    const hero = document.querySelector(".game-hero");
    if (!hero || hero.querySelector("[data-app-store-top]")) return;

    const marquee = hero.querySelector(".marquee");
    const band = document.createElement("section");
    band.className = "app-store-band app-store-band-top";
    band.dataset.appStoreTop = "";
    band.setAttribute("aria-label", "App Store");
    band.innerHTML = `
      <div class="shell app-store-band-inner">
        <a class="app-store-badge-link" href="https://apps.apple.com/" target="_blank" rel="noreferrer" aria-label="Download on the App Store">
          <img class="app-store-badge" src="images/app-store-badge.png" alt="Download on the App Store">
        </a>
      </div>
    `;

    if (marquee) {
      hero.insertBefore(band, marquee);
    } else {
      hero.appendChild(band);
    }
  }

  function apply(locale, updateUrl = true) {
    const page = document.body.dataset.page || "home";
    const strings = {
      ...(translations[locale] || translations.uk),
      ...(window.PATRON_COMMON_TRANSLATIONS?.[locale] || {})
    };
    const titleKey = pageTitleKeys[page] || "brand";
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    applyPageFragments(page, locale);
    ensureTopAppStoreBadge();
    document.title = titleKey === "brand"
      ? strings.brand
      : `${strings[titleKey]} — ${strings.brand}`;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const value = strings[element.dataset.i18n];
      if (value) element.textContent = value;
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
      const value = strings[element.dataset.i18nAria];
      if (value) element.setAttribute("aria-label", value);
    });

    document.querySelectorAll("[data-language-label]").forEach((label) => {
      label.textContent = languageLabels[locale] || languageLabels.uk;
    });
    selects.forEach((select) => {
      select.value = locale;
      select.setAttribute("aria-label", languageLabels[locale] || languageLabels.uk);
    });

    localStorage.setItem("patron-site-language", locale);
    updateInternalLinks(locale);

    if (updateUrl) {
      const url = new URL(location.href);
      url.searchParams.set("lang", locale);
      history.replaceState({}, "", url);
    }
  }

  selects.forEach((select) => {
    select.addEventListener("change", () => apply(select.value));
  });
  apply(initial, Boolean(requested));
