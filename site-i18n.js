  function normalize(value) {
    if (!value) return null;
    const exact = supported.find((code) => code.toLowerCase() === value.toLowerCase());
    if (exact) return exact;
    const prefix = value.toLowerCase().split("-")[0];
    return aliases[prefix] || supported.find((code) => code.split("-")[0] === prefix) || null;
  }

  document.querySelectorAll("[data-language-switcher]").forEach((container, index) => {
    const control = document.createElement("div");
    const label = document.createElement("label");
    const select = document.createElement("select");
    const id = index === 0 ? "language-select" : `language-select-${index + 1}`;

    control.className = "language-control";
    label.htmlFor = id;
    label.dataset.languageLabel = "";
    select.id = id;
    select.name = "language";

    Object.entries(languageNames).forEach(([code, name]) => {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = name;
      select.append(option);
    });

    control.append(label, select);
    container.replaceWith(control);
  });

